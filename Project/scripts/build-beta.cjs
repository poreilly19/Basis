// Create a minimal static deployment candidate. This script does not publish it.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const ROOT=path.join(__dirname,'..');
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
function betaHeaders(html){
  // Event-handler attributes need unsafe-inline; use registered listeners instead.
  if(/<[^>]+\son[a-z]+\s*=/i.test(html))throw Error('Inline event attributes must be removed before building the beta CSP.');
  const hashes=[];
  for(const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)){
    if(/\bsrc\s*=/i.test(match[1]))throw Error('Review external script tags before building the beta release.');
    if(/type=["']application\/x-basis-worker["']/i.test(match[1]))continue;
    hashes.push("'sha256-"+crypto.createHash('sha256').update(match[2]).digest('base64')+"'");
  }
  if(hashes.length!==3)throw Error('Expected three executable inline scripts; review the release CSP.');
  return {
    'Content-Security-Policy':[
      "default-src 'none'", "base-uri 'none'", "object-src 'none'", "frame-ancestors 'none'", "form-action 'none'",
      "script-src "+hashes.join(' ')+" blob: https://cdn.sheetjs.com 'wasm-unsafe-eval'",
      "style-src 'self' 'unsafe-inline'", "img-src 'self' blob: data:", "font-src 'self'", "worker-src 'self' blob:",
      "connect-src 'self' https://cdnjs.cloudflare.com https://api.openai.com https://api.anthropic.com",
      "manifest-src 'self'"
    ].join('; '),
    'X-Content-Type-Options':'nosniff','Referrer-Policy':'no-referrer','X-Frame-Options':'DENY',
    'Permissions-Policy':'camera=(), microphone=(), geolocation=(), payment=()',
    'Cache-Control':'no-store'
  };
}
function buildBeta(root=ROOT){
  const html=fs.readFileSync(path.join(root,'app/index.html'),'utf8'),version=JSON.parse(fs.readFileSync(path.join(root,'package.json'))).version;
  const headers=betaHeaders(html),files=new Map([['index.html',Buffer.from(html)]]);
  for(const [source,target]of [
    ['docs/BETA_404.html','404.html'],['docs/BETA_PRIVACY.html','privacy.html'],['docs/BETA_LIMITATIONS.html','limitations.html'],
    ['docs/THIRD_PARTY_NOTICES.md','THIRD_PARTY_NOTICES.txt'],
    ['docs/third_party/SHEETJS_LICENSE_0_20_3.txt','third_party/SHEETJS_LICENSE_0_20_3.txt'],
    ['docs/third_party/PDFJS_LICENSE_4_10_38.txt','third_party/PDFJS_LICENSE_4_10_38.txt']
  ])files.set(target,fs.readFileSync(path.join(root,source)));
  const runtime=JSON.parse(fs.readFileSync(path.join(root,'tests/fixtures/runtime_dependencies.json')));
  files.set('runtime-inventory.json',Buffer.from(JSON.stringify({scope:'Direct optional runtime artifacts; not a complete transitive SBOM',artifacts:runtime.artifacts.filter(a=>a.purpose!=='compatibility-reference-only')},null,2)+'\n'));
  files.set('headers.json',Buffer.from(JSON.stringify(headers,null,2)+'\n'));
  files.set('_headers',Buffer.from('/*\n'+Object.entries(headers).map(([name,value])=>'  '+name+': '+value).join('\n')+'\n'));
  const release={generator:'basis-beta-static-v1',version,channel:'beta-candidate',appSha256:sha(files.get('index.html')),accessControl:'Hosting must enforce tester access before serving any files; this static bundle does not implement login.',files:Object.fromEntries([...files].map(([name,bytes])=>[name,{bytes:bytes.length,sha256:sha(bytes)}]))};
  files.set('release.json',Buffer.from(JSON.stringify(release,null,2)+'\n'));
  const dist=path.join(root,'dist'),target=path.join(dist,'basis-beta');fs.mkdirSync(dist,{recursive:true});
  if(fs.existsSync(target)){
    if(fs.lstatSync(target).isSymbolicLink())throw Error('Refusing to replace a linked deployment directory.');
    let prior;try{const marker=path.join(target,'release.json'),stat=fs.lstatSync(marker);if(stat.isFile()&&!stat.isSymbolicLink()&&stat.size<=65536)prior=JSON.parse(fs.readFileSync(marker));}catch(ignore){}
    if(prior?.generator!=='basis-beta-static-v1')throw Error('The deployment directory contains files not generated by this builder. Move it before building.');
    // Do not discard user additions or edits merely because a release marker
    // remains. Only replace the exact, unmodified previous generated inventory.
    const entries=prior.files;
    if(!entries||typeof entries!=='object'||Array.isArray(entries)||Object.keys(entries).length>100)throw Error('Invalid previous deployment inventory. Move it before building.');
    const expected=new Set(['release.json']);
    for(const [name,record]of Object.entries(entries)){
      if(!/^[A-Za-z0-9_.-]+(?:\/[A-Za-z0-9_.-]+)*$/.test(name)||name.split('/').some(p=>p==='.'||p==='..')||name==='release.json'||!record||!Number.isInteger(record.bytes)||record.bytes<0||record.bytes>16*1024*1024||typeof record.sha256!=='string'||!/^\w{64}$/.test(record.sha256))throw Error('Invalid previous deployment inventory. Move it before building.');
      expected.add(name);
    }
    const seen=new Set();
    function inspect(directory,prefix=''){
      for(const item of fs.readdirSync(directory)){
        const name=prefix+item,file=path.join(directory,item),stat=fs.lstatSync(file);
        if(stat.isSymbolicLink())throw Error('Modified deployment contains a link. Move it before building.');
        if(stat.isDirectory()){
          if(![...expected].some(n=>n.startsWith(name+'/')))throw Error('Modified deployment contains an extra directory. Move it before building.');
          inspect(file,name+'/');
        }else{
          if(!stat.isFile()||!expected.has(name))throw Error('Modified deployment contains extra files. Move it before building.');
          if(name!=='release.json'&&(stat.size!==entries[name].bytes||sha(fs.readFileSync(file))!==entries[name].sha256))throw Error('Modified deployment file: '+name+'. Move it before building.');
          seen.add(name);
        }
      }
    }
    inspect(target);if(seen.size!==expected.size)throw Error('Previous deployment has missing files. Move it before building.');
  }
  const staging=fs.mkdtempSync(path.join(dist,'.basis-beta-'));
  try{for(const [name,bytes]of files){const file=path.join(staging,name);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,bytes);}if(fs.existsSync(target))fs.rmSync(target,{recursive:true});fs.renameSync(staging,target);}
  finally{if(fs.existsSync(staging))fs.rmSync(staging,{recursive:true});}
  return {directory:target,release,headers};
}
if(require.main===module){const out=buildBeta();console.log(JSON.stringify({directory:out.directory,version:out.release.version,appSha256:out.release.appSha256,files:Object.keys(out.release.files).length+1},null,2));}
module.exports={betaHeaders,buildBeta};
